// shared/message-delivery.js
// End-to-end delivery proof for model messages. Every outgoing prompt carries a per-model token
// that the model repeats on its last line. An incoming answer is:
//   verified — contains its own token;
//   missing  — final answer without the token (shown, marked "attribution unverified");
//   foreign  — contains another request's token (a stale answer: not shown).
// The token is secondary evidence: request ownership is decided by transportRequestId
// (TransportContract). Tokens are registered per transport request, so preparing a new
// request never invalidates the token of a request that is still in flight.
// Only our own transport tags are removed; the answer content is never rewritten otherwise.
// The journal is mirrored to chrome.storage.session for the telemetry window (Automation tab).
(function initMessageDelivery(root) {
  'use strict';

  const JOURNAL_KEY = 'messageDelivery.journal.v2';
  // Characters of a received answer kept in the journal (final events and their raw artifact).
  // 1200 hid the accepted text from diagnosis of long answers (review C11, L-18).
  const JOURNAL_ANSWER_LIMIT = 4000;
  // A multi-stage run of ten models produces ~20 events per message.
  const JOURNAL_LIMIT = 3000;
  const EXPECTED_LIMIT = 200;
  const FOCUS_EVENTS_PER_REQUEST = 30;
  const TOKEN_RE = /\[\[AO-[a-z0-9]{6}\]\]/gi;
  const INSTRUCTION = 'Последней строкой ответа напиши только метку';
  const INSTRUCTION_RE = new RegExp(`^.*${INSTRUCTION}.*$`, 'gim');
  // Only the judge-prompt response delimiters (shared/judge-prompt-builder.js) are
  // transport tags. Generic <<<...>>> is user content (CUDA launches, templates).
  const RESPONSE_MARKER_RE = /(?:<<<|&lt;&lt;&lt;)RESPONSE [^\n<>&]{1,200}? (?:START|END)(?:>>>|&gt;&gt;&gt;)/g;

  const expectedByRequest = new Map(); // transportRequestId -> entry
  const latestByModel = new Map(); // model -> entry (requests without a transport id)
  const lastStatusByModel = new Map(); // model -> last unassigned status
  const journal = [];
  const producerId = `prod_${Date.now()}_${Math.random().toString(36).slice(2, 9)}`;
  let producerSeq = 0;
  let unconfirmedQueue = [];
  let appendTimer = null;
  let appendFlight = false;
  let appendEpoch = 0;
  let mirrorTimer = null;
  const collection = { recorded: 0, evicted: 0, focusDetailsOmitted: 0, limit: JOURNAL_LIMIT, focusDetailLimit: FOCUS_EVENTS_PER_REQUEST };
  const proof = root.AnswerProofNormalization || (typeof require === 'function' ? require('./answer-proof-normalization') : null);
  const textArtifact = (text, limit, representation, identity = {}) => ({
    representation, lengthUnit: 'UTF-16 code units', fullLength: text.length, storedLength: Math.min(text.length, limit),
    storageLimit: limit, truncated: text.length > limit, ...(proof?.evidence(text, identity) || {})
  });

  function makeToken() {
    const bytes = new Uint8Array(6);
    (root.crypto || globalThis.crypto).getRandomValues(bytes);
    return `AO-${Array.from(bytes, (b) => 'abcdefghjkmnpqrstuvwxyz23456789'[b % 31]).join('')}`;
  }

  const tag = (token) => `[[${token}]]`;

  function wrap(prompt, token, instruction = `${INSTRUCTION} {метка}`) {
    const value = String(instruction);
    // The instruction is editable; the unique proof token remains generated by transport.
    const suffix = value.includes('{метка}') ? value.replace(/\{метка\}/g, tag(token)) : `${value}${value ? ' ' : ''}${tag(token)}`;
    return `${String(prompt || '').trimEnd()}\n\n${suffix}`;
  }

  // Provider chrome after the token ("[[AO-…]] 8:55pm": Le Chat appends the time) is not the
  // answer. The token is the last line of the answer, so a short tail after it is dropped;
  // otherwise the ending check would read "8:55pm" as a cut-off sentence.
  const TAIL_AFTER_TOKEN_RE = /(\[\[AO-[a-z0-9]{6}\]\])[ \t]*[^\n\[]{0,40}$/gim;

  function clean(text) {
    return String(text || '')
      .replace(TAIL_AFTER_TOKEN_RE, '$1')
      .replace(TOKEN_RE, '')
      .replace(INSTRUCTION_RE, '')
      .replace(RESPONSE_MARKER_RE, '')
      .replace(/[ \t]+$/gm, '')
      .replace(/\n{3,}/g, '\n\n')
      .trim();
  }

  // HTML answers: the same tags appear as plain text inside the markup.
  function cleanHtml(html) {
    return String(html || '')
      .replace(TOKEN_RE, '')
      .replace(RESPONSE_MARKER_RE, '')
      // The token sat at the end of a block after a space ("… proof. [[AO-…]]</p>"): drop the space it leaves.
      .replace(/[ \t]+(<\/(?:p|div|li)>)/gi, '$1')
      .replace(/<(p|div|li)[^>]*>\s*(?:<br\s*\/?>)?\s*<\/\1>/gi, '');
  }

  function inspect(text, token) {
    if (!token) return 'untracked';
    if (proof?.hasDeliveryTokenTail?.(text, tag(token))) return 'verified';
    // Our token elsewhere in the text is a quoted instruction or an echo, not the end of the answer.
    const ours = tag(token).toLowerCase();
    const found = String(text || '').match(TOKEN_RE) || [];
    return found.some((value) => value.toLowerCase() !== ours) ? 'foreign' : 'missing';
  }

  function scheduleAppend() {
    if (appendTimer) return;
    appendTimer = setTimeout(() => {
      appendTimer = null;
      void flushAppend();
    }, 40);
  }

  async function flushAppend() {
    if (appendFlight || unconfirmedQueue.length === 0) return;
    const runtime = root.chrome?.runtime || globalThis.chrome?.runtime;
    if (!runtime?.sendMessage) return;
    appendFlight = true;
    const epochAtStart = appendEpoch;
    const batch = unconfirmedQueue.slice();
    try {
      await new Promise((resolve) => {
        runtime.sendMessage({ type: 'DELIVERY_JOURNAL_APPEND', events: batch, producerId }, (res) => {
          if (appendEpoch === epochAtStart) {
            if (!runtime.lastError && res?.ok) {
              const batchIds = new Set(batch.map((e) => e.eventId));
              unconfirmedQueue = unconfirmedQueue.filter((e) => !batchIds.has(e.eventId));
            }
          }
          resolve();
        });
      });
    } catch (_) {
      // Keep in queue on error if epoch matches
    } finally {
      appendFlight = false;
      if (appendEpoch === epochAtStart && unconfirmedQueue.length > 0) scheduleAppend();
    }
  }

  function record(event) {
    if (!event.eventId) {
      if (event.sourceEventId) {
        const ord = Number.isInteger(event.ordinal) ? event.ordinal : 0;
        event.eventId = `${event.sourceEventId}:${event.kind || 'evt'}:${ord}`;
      } else {
        event.eventId = `${producerId}:${++producerSeq}`;
      }
    }
    const item = { at: new Date().toISOString(), ...event };
    journal.push(item);
    collection.recorded += 1;
    if (journal.length > JOURNAL_LIMIT) { collection.evicted += journal.length - JOURNAL_LIMIT; journal.splice(0, journal.length - JOURNAL_LIMIT); }
    unconfirmedQueue.push(item);
    scheduleAppend();
  }

  const completionOf = (status, text) => {
    const contract = root.TransportContract || globalThis.TransportContract;
    return contract?.classifyCompletion ? contract.classifyCompletion(status, text) : null;
  };

  const requestIdOf = (message) => String(message?.transportRequestId || message?.metadata?.transportRequestId || message?.meta?.transportRequestId || '') || null;

  function resolveObservedEntry(message) {
    const explicitId = requestIdOf(message);
    if (explicitId) {
      const entry = expectedByRequest.get(explicitId) || null;
      if (entry) {
        return {
          entry,
          requestId: explicitId,
          sourceTransportRequestId: explicitId,
          attemptCorrelation: 'linked',
          correlationReason: null
        };
      }
      return {
        entry: null,
        requestId: null,
        sourceTransportRequestId: explicitId,
        attemptCorrelation: 'unassigned',
        correlationReason: 'unknown_request_id'
      };
    }
    const tabId = message?.tabId ?? message?.data?.tabId ?? message?.meta?.tabId ?? message?.metadata?.tabId ?? (message?.sender?.tab?.id != null ? message.sender.tab.id : null);
    if (tabId != null) {
      const activeEntries = [];
      const seenEntries = new Set();
      expectedByRequest.forEach((ent) => {
        if (!ent.final && !seenEntries.has(ent)) {
          seenEntries.add(ent);
          activeEntries.push(ent);
        }
      });
      const matches = activeEntries.filter((ent) => ent.tabId === tabId && (!message.llmName || ent.model === message.llmName));
      if (matches.length === 1) {
        const entry = matches[0];
        return {
          entry,
          requestId: entry.requestId || null,
          sourceTransportRequestId: null,
          attemptCorrelation: 'linked',
          correlationReason: 'tab_bound'
        };
      }
      if (matches.length > 1) {
        return {
          entry: null,
          requestId: null,
          sourceTransportRequestId: null,
          attemptCorrelation: 'conflict',
          correlationReason: 'ambiguous_tab_binding'
        };
      }
      return {
        entry: null,
        requestId: null,
        sourceTransportRequestId: null,
        attemptCorrelation: 'unassigned',
        correlationReason: 'unbound_tab'
      };
    }
    return {
      entry: null,
      requestId: null,
      sourceTransportRequestId: null,
      attemptCorrelation: 'unassigned',
      correlationReason: 'missing_request_id'
    };
  }

  function pruneExpected() {
    if (expectedByRequest.size <= EXPECTED_LIMIT) return;
    const overflow = expectedByRequest.size - EXPECTED_LIMIT;
    Array.from(expectedByRequest.keys()).slice(0, overflow).forEach((key) => expectedByRequest.delete(key));
  }

  // Outgoing: one token per model; returns the per-model prompt map to dispatch.
  // The journal records 'prepared': nothing has been sent yet at this point.
  function prepare({ prompt, promptsByModel, models, batchId = '', requestIds = null, promptLineageByModel = null, instructionsByModel = null }) {
    const out = {};
    models.forEach((model) => {
      const token = makeToken();
      const base = promptsByModel?.[model] ?? prompt;
      const requestId = String(requestIds?.[model] || '') || null;
      out[model] = wrap(base, token, instructionsByModel?.[model]);
      const promptArtifact = textArtifact(out[model], 1500, 'wrapped_prompt');
      const entry = { token, sentAt: Date.now(), batchId, final: false, model, requestId, promptArtifact };
      if (requestId) expectedByRequest.set(requestId, entry);
      latestByModel.set(model, entry);
      record({ kind: 'prepared', model, token, batchId, requestId, chars: out[model].length, promptArtifact, promptLineage: promptLineageByModel?.[model] ?? null, prompt: out[model].slice(0, 1500) });
    });
    pruneExpected();
    return out;
  }

  function entryFor(message) {
    const requestId = requestIdOf(message);
    if (requestId) return expectedByRequest.get(requestId) || null;
    const model = message?.llmName;
    return model ? latestByModel.get(model) || null : null;
  }

  function cleanMessage(message, metadata, { tracked = true } = {}) {
    const answer = message.answer && typeof message.answer === 'object'
      ? String(message.answer.text || message.answer.answer || '')
      : String(message.answer || '');
    const cleaned = { ...message };
    if (tracked || message.metadata) cleaned.metadata = metadata;
    if (message.answer && typeof message.answer === 'object') {
      cleaned.answer = { ...message.answer, text: clean(answer), html: cleanHtml(message.answer.html || message.answer.answerHtml || '') };
    } else {
      cleaned.answer = clean(answer);
    }
    if (message.answerHtml) cleaned.answerHtml = cleanHtml(message.answerHtml);
    if (message.html) cleaned.html = cleanHtml(message.html);
    return cleaned;
  }

  // A body that is only a progress or noise line: short, no content, a progress verb without a verdict.
  // The classifier is the same one that judges the answer (shared/answer-content-classifier.js).
  function isProgressOnlyBody(body) {
    const classifier = root.AnswerContentClassifier
      || (typeof module !== 'undefined' && module.exports ? require('./answer-content-classifier.js') : null);
    return Boolean(classifier && classifier.isProgressOnlyBody(String(body || '').trim()));
  }

  // Incoming: returns null when the message must be dropped (stale answer),
  // otherwise the message with cleaned text/html and attribution metadata.
  function receive(message, { final = false } = {}) {
    if (!message) return message;
    const entry = entryFor(message);
    // Unknown request (e.g. the panel was reloaded): still strip our transport
    // tags so a token never leaks into the feed or into the next stage prompt.
    if (!entry) return cleanMessage(message, { ...(message.metadata || {}) }, { tracked: false });
    const model = message.llmName;
    const answer = message.answer && typeof message.answer === 'object'
      ? String(message.answer.text || message.answer.answer || '')
      : String(message.answer || '');
    const state = inspect(answer, entry.token);
    const answerArtifacts = { raw: textArtifact(answer, JOURNAL_ANSWER_LIMIT, 'received_with_transport_tags', message.metadata || {}),
      cleaned: textArtifact(clean(answer), 0, 'transport_tags_removed', message.metadata || {}), transformation: 'MessageDelivery.clean' };
    if (state === 'foreign') {
      if (!entry.staleLogged) { entry.staleLogged = true; record({ kind: 'stale_dropped', model, token: entry.token, requestId: entry.requestId, chars: answer.length, answer: answer.slice(0, 500) }); }
      return null;
    }
    const metadata = { ...(message.metadata || {}) };
    // Preserve proof after removing the transport token from the visible text.
    const tokenAt = answer.toLowerCase().lastIndexOf(tag(entry.token).toLowerCase());
    const endMarkerSeen = state === 'verified'
      && tokenAt >= 0 && answer.length - tokenAt - tag(entry.token).length <= 40
      && Boolean(clean(answer));
    // A marker after a progress line («Проверю…») is not the end of the answer (review L-2).
    const progressOnly = endMarkerSeen && isProgressOnlyBody(clean(answer));
    if (endMarkerSeen && !progressOnly) entry.answerEndMarkerSeen = true;
    metadata.answerEndMarkerSeen = entry.answerEndMarkerSeen === true;
    if (metadata.answerEndMarkerSeen) {
      metadata.terminal = true;
      metadata.status = 'SUCCESS';
    }
    if (progressOnly) {
      metadata.status = 'PARTIAL';
      metadata.reason = 'progress_only';
    }
    if (!final && entry.final && entry.finalKind === 'empty_answer' && answer.trim() && !entry.lateTextLogged) {
      entry.lateTextLogged = true;
      record({ kind: 'late_text', model, token: entry.token, requestId: entry.requestId, chars: answer.length, ms: Date.now() - entry.sentAt });
    }
    // Growth of the answer text, sampled at most every 10 s: shows whether the
    // model kept writing and when it stopped.
    if (!final && answer.trim() && entry.firstText && answer.length !== entry.lastTextChars
      && Date.now() - (entry.lastTextLoggedAt || 0) >= 10000) {
      entry.lastTextLoggedAt = Date.now();
      record({ kind: 'text_progress', model, token: entry.token, requestId: entry.requestId, chars: answer.length, ms: Date.now() - entry.sentAt });
    }
    if (answer.trim()) entry.lastTextChars = answer.length;
    if (answer.trim() && !entry.firstText) {
      entry.firstText = true;
      entry.lastTextLoggedAt = Date.now();
      record({ kind: 'first_text', model, token: entry.token, requestId: entry.requestId, chars: answer.length, ms: Date.now() - entry.sentAt });
    }
    if (final && !entry.final) {
      entry.final = true;
      // A final that holds only transport marks (the tag, the instruction) is empty too.
      const bodyEmpty = !clean(answer);
      const kind = bodyEmpty ? 'empty_answer' : state === 'verified' ? 'verified' : 'missing_token';
      // An empty final is a failure whatever status the adapter reported: the journal
      // must not say "success" next to chars=0 (review C4).
      const status = bodyEmpty ? 'FAILED' : String(message.status || metadata.status || metadata.finalStatus || '');
      entry.finalKind = kind;
      record({
        kind, model, token: entry.token, requestId: entry.requestId, chars: answer.length, ms: Date.now() - entry.sentAt,
        answer: answer.slice(0, JOURNAL_ANSWER_LIMIT), answerArtifacts,
        status,
        completion: completionOf(status || (answer.trim() ? 'SUCCESS' : 'FAILED'), answer),
        dispatchId: message.dispatchId || metadata.dispatchId || null,
        source: String(metadata.source || metadata.answerSource || 'live'),
        reason: String(metadata.reason || metadata.completionReason || metadata.failureClass || metadata.hardStopReason || ''),
        detail: [metadata.errorType, metadata.errorMessage].filter(Boolean).join(': ') || null
      });
    } else if (final && entry.final && entry.finalKind === 'empty_answer' && clean(answer)) {
      // A usable answer upgraded an earlier empty/failed terminal of the same request.
      const status = String(message.status || metadata.status || metadata.finalStatus || '');
      entry.finalKind = state === 'verified' ? 'verified' : 'missing_token';
      record({
        kind: entry.finalKind, model, token: entry.token, requestId: entry.requestId, chars: answer.length, ms: Date.now() - entry.sentAt,
        status, completion: completionOf(status || 'SUCCESS', answer), dispatchId: message.dispatchId || metadata.dispatchId || null,
        source: String(metadata.source || metadata.answerSource || 'live'), answerArtifacts, reason: 'upgraded_after_failure'
      });
    } else if (final && entry.final && metadata.revision === true) {
      record({ kind: 'revision', model, token: entry.token, requestId: entry.requestId, chars: answer.length, answerArtifacts, reason: String(metadata.reason || '') });
    }
    if (final && state === 'missing') {
      metadata.attributionState = 'unproven';
      metadata.attributionLabel = 'Без метки доставки';
    }
    const out = cleanMessage(message, metadata);
    // The panel must not show an empty final as a success whatever status arrived with it.
    if (final && !clean(answer)) {
      out.status = 'FAILED';
      out.metadata = { ...(out.metadata || {}), status: 'FAILED' };
    }
    return out;
  }

  // Runtime facts the background already broadcasts: model statuses, opened tabs,
  // dispatch phases (TRANSPORT_DISPATCH_PHASE) and provider stop results.
  function observeRuntime(message) {
    if (!message) return;
    const sourceEventId = String(message.sourceEventId || message.meta?.sourceEventId || '') || null;
    if (message.type === 'TRANSPORT_DISPATCH_PHASE') {
      const entry = entryFor(message);
      if (entry && message.tabId != null) {
        entry.tabId = message.tabId;
      }
      const phaseKey = `${requestIdOf(message)}|${message.phase}|${message.dispatchId}|${message.at || ''}`;
      if (entry && entry.lastPhaseKey === phaseKey) return;
      if (entry) entry.lastPhaseKey = phaseKey;
      record({
        kind: 'dispatch', model: message.llmName, token: entry?.token || null, requestId: requestIdOf(message),
        sourceEventId, ordinal: 0,
        phase: String(message.phase || ''), dispatchId: message.dispatchId || null, tabId: message.tabId ?? null,
        reason: message.reason || null, dispatchReason: message.dispatchReason || null, attempt: message.attempt ?? null,
        promptArtifact: message.phase === 'submitted' ? entry?.promptArtifact || null : undefined,
        promptIdentityProven: Boolean(message.phase === 'submitted' && message.promptHash && message.promptHash === entry?.promptArtifact?.normalizedHash && message.promptNormalizationVersion === entry?.promptArtifact?.normalizationVersion),
        submittedPromptHash: message.promptHash ?? null,
        submittedPromptNormalizationVersion: message.promptNormalizationVersion ?? null,
        promptProofScope: message.promptProofScope ?? null,
        bg: message.backgroundVersion || null, answerChars: message.answerChars ?? null,
        ms: entry ? Date.now() - entry.sentAt : null
      });
      return;
    }
    if (message.type === 'TRANSPORT_FOCUS') {
      const explicitId = requestIdOf(message);
      const resolved = resolveObservedEntry(message);
      const entry = resolved.entry;
      const eventReason = message.source || null;
      const correlationReason = resolved.correlationReason || null;
      const recordReason = correlationReason === 'unknown_request_id'
        ? correlationReason
        : (eventReason || correlationReason);
      if (entry && !entry.final) {
        entry.focusCount = (entry.focusCount || 0) + 1;
        // The count is exact; the first events carry the detail, the rest only the count.
        if (entry.focusCount <= FOCUS_EVENTS_PER_REQUEST) {
          record({
            kind: 'focus', model: message.llmName || entry.model || null, token: entry.token,
            requestId: resolved.requestId, sourceTransportRequestId: explicitId || null,
            sourceEventId, ordinal: entry.focusCount,
            attemptCorrelation: resolved.attemptCorrelation, correlationReason, reason: recordReason,
            source: message.source || null, tabId: message.tabId ?? entry.tabId ?? null, n: entry.focusCount, ms: Date.now() - entry.sentAt
          });
        } else {
          collection.focusDetailsOmitted += 1;
          if (entry.focusCount % 10 === 0) {
            record({
              kind: 'focus_count', model: message.llmName || entry.model || null, token: entry.token,
              requestId: resolved.requestId, sourceTransportRequestId: explicitId || null,
              sourceEventId, ordinal: entry.focusCount,
              attemptCorrelation: resolved.attemptCorrelation, correlationReason, reason: recordReason,
              n: entry.focusCount, ms: Date.now() - entry.sentAt
            });
          }
        }
      } else if (!entry) {
        record({
          kind: 'focus', model: message.llmName || null, token: null,
          requestId: null, sourceTransportRequestId: explicitId || null,
          sourceEventId, ordinal: 0,
          attemptCorrelation: resolved.attemptCorrelation, correlationReason, reason: recordReason,
          source: message.source || null, tabId: message.tabId ?? null
        });
      }
      return;
    }
    if (message.type === 'LLM_COMPLETION_TERMINAL') {
      const explicitId = requestIdOf(message);
      const resolved = resolveObservedEntry(message);
      const entry = resolved.entry;
      const result = message.meta?.terminalResult || {};
      const eventReason = result.reason || null;
      const correlationReason = resolved.correlationReason || null;
      const recordReason = correlationReason === 'unknown_request_id'
        ? correlationReason
        : (eventReason || correlationReason);
      record({
        kind: 'completion_terminal', model: message.llmName || entry?.model || null, token: entry?.token || null,
        requestId: resolved.requestId, sourceTransportRequestId: explicitId || null,
        sourceEventId, ordinal: 0,
        attemptCorrelation: resolved.attemptCorrelation, correlationReason, reason: recordReason,
        status: result.status || null, dispatchId: message.meta?.dispatchId || null,
        ms: entry ? Date.now() - entry.sentAt : null
      });
      return;
    }
    if (message.type === 'SPA_NAVIGATION') {
      const explicitId = requestIdOf(message);
      const resolved = resolveObservedEntry(message);
      const entry = resolved.entry;
      const path = (url) => { try { return new URL(url).pathname; } catch (_) { return String(url || ''); } };
      const eventReason = message.reason || null;
      const correlationReason = resolved.correlationReason || null;
      const recordReason = correlationReason === 'unknown_request_id'
        ? correlationReason
        : (eventReason || correlationReason);
      record({
        kind: 'navigation', model: message.llmName || entry?.model || null, token: entry?.token || null,
        requestId: resolved.requestId, sourceTransportRequestId: explicitId || null,
        sourceEventId, ordinal: 0,
        attemptCorrelation: resolved.attemptCorrelation, correlationReason, reason: recordReason,
        from: path(message.oldUrl), to: path(message.newUrl),
        ms: entry ? Date.now() - entry.sentAt : null
      });
      return;
    }
    if (message.type === 'PROVIDER_STOP_RESULT') {
      const explicitId = requestIdOf(message);
      const resolved = resolveObservedEntry(message);
      const entry = resolved.entry;
      const eventReason = message.reason || null;
      const correlationReason = resolved.correlationReason || null;
      const recordReason = correlationReason === 'unknown_request_id'
        ? correlationReason
        : (eventReason || correlationReason);
      record({
        kind: 'provider_stop', model: message.llmName || entry?.model || null, token: entry?.token || null,
        requestId: resolved.requestId, sourceTransportRequestId: explicitId || null,
        sourceEventId, ordinal: 0,
        attemptCorrelation: resolved.attemptCorrelation, correlationReason, reason: recordReason,
        stopped: message.stopped === true
      });
      return;
    }
    if (message.type === 'STATUS_UPDATE') {
      const explicitId = requestIdOf(message);
      const resolved = resolveObservedEntry(message);
      const entry = resolved.entry;
      const status = String(message.status || '').toUpperCase();
      const correlationReason = resolved.correlationReason || null;
      const recordReason = resolved.attemptCorrelation === 'unassigned' ? correlationReason : null;
      if (entry) {
        if (entry.final || !status || entry.lastStatus === status) return;
        entry.lastStatus = status;
        entry.statusCount = (entry.statusCount || 0) + 1;
        record({
          kind: 'status', model: message.llmName || entry.model, token: entry.token,
          requestId: resolved.requestId, sourceTransportRequestId: explicitId || null,
          sourceEventId, ordinal: entry.statusCount,
          attemptCorrelation: resolved.attemptCorrelation, correlationReason, reason: recordReason,
          status
        });
      } else {
        if (!status) return;
        const model = message.llmName || null;
        if (model) {
          if (lastStatusByModel.get(model) === status) return;
          lastStatusByModel.set(model, status);
        }
        record({
          kind: 'status', model, token: null,
          requestId: null, sourceTransportRequestId: explicitId || null,
          sourceEventId, ordinal: 0,
          attemptCorrelation: resolved.attemptCorrelation, correlationReason, reason: recordReason,
          status
        });
      }
      return;
    } else if (message.type === 'GLOBAL_STATE_BROADCAST') {
      const map = message.state?.tabs?.map || {};
      let ord = 0;
      latestByModel.forEach((entry, model) => {
        if (Number.isInteger(map[model])) entry.tabId = map[model];
        if (entry.tabSeen || entry.final || !Number.isInteger(map[model])) return;
        entry.tabSeen = true;
        ord += 1;
        record({
          kind: 'tab', model, token: entry.token, requestId: entry.requestId,
          sourceEventId, ordinal: ord,
          tabId: map[model], ms: Date.now() - entry.sentAt
        });
      });
    }
  }

  // The batch finished waiting: models that never produced a final answer.
  function closeBatch({ models = [], timedOut = false, failed = {}, requestIds = null, cancelled = false, reason = '' } = {}) {
    models.forEach((model) => {
      const requestId = String(requestIds?.[model] || '') || null;
      const entry = requestId ? expectedByRequest.get(requestId) : latestByModel.get(model);
      if (!entry || entry.final) return;
      entry.final = true;
      record({
        kind: cancelled ? 'cancelled' : 'no_answer', model, token: entry.token, requestId: entry.requestId,
        ms: Date.now() - entry.sentAt, timedOut, status: String(failed[model] || ''), reason: String(reason || '')
      });
    });
  }

  // Batch-level facts from the panel (start, refusals, acceptance, outcome) and
  // answers the panel refused for their identity. Not tied to one token.
  function batchEvent(kind, fields = {}) {
    const payload = { ...fields };
    if ('kind' in payload && payload.kind !== kind) {
      if (!payload.stepKind && (kind.startsWith('custom_step') || payload.kind === 'round' || payload.kind === 'owner')) {
        payload.stepKind = payload.kind;
      }
      if (!payload.waitKind && (kind.startsWith('custom_wait') || ['decision', 'owner', 'asks', 'unknown'].includes(payload.kind))) {
        payload.waitKind = payload.kind;
      }
      delete payload.kind;
    }
    record({ ...payload, kind });
  }

  async function snapshot() {
    const runtime = root.chrome?.runtime || globalThis.chrome?.runtime;
    if (runtime?.sendMessage) {
      try {
        const resp = await new Promise((resolve) => {
          runtime.sendMessage({ type: 'DELIVERY_JOURNAL_SNAPSHOT' }, (res) => {
            if (runtime.lastError || !res?.ok) resolve(null);
            else resolve(res.snapshot);
          });
        });
        if (resp && Array.isArray(resp.events)) {
          const seen = new Set(resp.events.map((e) => e.eventId));
          const unconfirmed = unconfirmedQueue.filter((e) => e.eventId && !seen.has(e.eventId));
          const merged = resp.events.concat(unconfirmed);
          return {
            version: 2,
            events: merged,
            collection: {
              ...(resp.collection || {}),
              retained: merged.length,
              unconfirmedTail: unconfirmed.length
            }
          };
        }
      } catch (_) {}
    }
    return {
      version: 2,
      events: journal.slice(),
      collection: { retained: journal.length, localOnly: true }
    };
  }

  // Clears only the journal; tokens of requests still in flight stay valid.
  function clearJournal() {
    appendEpoch += 1;
    if (appendTimer) {
      clearTimeout(appendTimer);
      appendTimer = null;
    }
    journal.length = 0;
    unconfirmedQueue.length = 0;
    const runtime = root.chrome?.runtime || globalThis.chrome?.runtime;
    if (runtime?.sendMessage) {
      try { runtime.sendMessage({ type: 'DELIVERY_JOURNAL_CLEAR' }, () => {}); } catch (_) {}
    }
    try {
      const sess = root.chrome?.storage?.session || globalThis.chrome?.storage?.session;
      sess?.remove?.(JOURNAL_KEY);
    } catch (_) { /* ignore */ }
  }

  function reset() {
    appendEpoch += 1;
    if (appendTimer) {
      clearTimeout(appendTimer);
      appendTimer = null;
    }
    expectedByRequest.clear();
    latestByModel.clear();
    lastStatusByModel.clear();
    journal.length = 0;
    unconfirmedQueue.length = 0;
    producerSeq = 0;
    const runtime = root.chrome?.runtime || globalThis.chrome?.runtime;
    if (runtime?.sendMessage) {
      try { runtime.sendMessage({ type: 'DELIVERY_JOURNAL_CLEAR' }, () => {}); } catch (_) {}
    }
    try {
      const sess = root.chrome?.storage?.session || globalThis.chrome?.storage?.session;
      sess?.remove?.(JOURNAL_KEY);
    } catch (_) { /* ignore */ }
  }

  const api = Object.freeze({ JOURNAL_KEY, isProgressOnlyBody, makeToken, wrap, clean, cleanHtml, inspect, prepare, receive, observeRuntime, closeBatch, batchEvent, record, snapshot, clearJournal, reset, collection: () => ({ ...collection, retained: journal.length }), journal: () => journal.slice() });
  root.MessageDelivery = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
